function Get-Lang {
    $l = [string]$script:Cfg.language
    if ($Strings.ContainsKey($l)) { return $l }
    return 'en'
}

# Culture for dates and weekday names in the current language.
function Get-LangCulture {
    $c = @{ en = 'en-US'; ru = 'ru-RU'; fr = 'fr-FR' }[(Get-Lang)]
    return [System.Globalization.CultureInfo]::GetCultureInfo($c)
}

function T([string]$key, $default = $key) {
    $s = $Strings[(Get-Lang)][$key]
    if ($null -eq $s) { $s = $Strings.en[$key] }
    if ($null -eq $s) { return $default }
    return $s
}

# "1 session" / "5 sessions"; French takes the singular for 0 too, Russian has three forms.
function Format-Count([int]$n, [string]$key) {
    $f = T "plural.$key"
    if ($f.Count -eq 2) {
        $one = $n -eq 1 -or ($n -eq 0 -and (Get-Lang) -eq 'fr')
        return "$n $(if ($one) { $f[0] } else { $f[1] })"
    }
    $d = $n % 10; $h = $n % 100
    if ($d -eq 1 -and $h -ne 11) { return "$n $($f[0])" }
    if ($d -ge 2 -and $d -le 4 -and ($h -lt 12 -or $h -gt 14)) { return "$n $($f[1])" }
    return "$n $($f[2])"
}
